const express = require("express");
const { auth } = require("../middleware/auth");
const c = require("../controllers/ticketController");
const router = express.Router();
router.use(auth);
router.get("/metadata", c.metadata);
router.get("/assignments", c.assignments);
router.get("/deletion-log", c.deletionLog);
router.delete("/", c.deleteAll);
router.get("/dashboard", c.dashboard);
router.get("/", c.list);
router.post("/", c.create);
router.patch("/:id", c.update);
router.delete("/:id", c.deleteOne);
router.post("/:id/comments", c.comment);
module.exports = router;
