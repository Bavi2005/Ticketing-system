const express = require("express");
const { auth } = require("../middleware/auth");
const { ticketUpload, persistTicketFiles } = require("../utils/upload");
const withAttachments = [ticketUpload.array("attachments", 5), persistTicketFiles];
const c = require("../controllers/ticketController");
const router = express.Router();
router.use(auth);
router.get("/metadata", c.metadata);
router.get("/assignments", c.assignments);
router.get("/deletion-log", c.deletionLog);
router.delete("/", c.deleteAll);
router.get("/dashboard", c.dashboard);
router.get("/", c.list);
router.post("/", ...withAttachments, c.create);
router.patch("/:id", c.update);
router.delete("/:id", c.deleteOne);
router.post("/:id/comments", ...withAttachments, c.comment);
module.exports = router;
